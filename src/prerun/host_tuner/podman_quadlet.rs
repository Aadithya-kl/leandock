#![cfg(target_os = "linux")]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::backup::atomic_write_bytes;
use crate::error::Result;
use crate::prerun::compose_parser::ParsedCompose;
use crate::prerun::db_tuner::OptimizationPlan;
use crate::prerun::host_tuner::scan_podman_compatibility;

/// Result of exporting a Compose stack into native systemd Quadlet units (daemonless Podman).
#[derive(Debug, Clone)]
pub struct QuadletExportReport {
    pub output_dir: PathBuf,
    pub generated_files: Vec<PathBuf>,
    pub warnings: Vec<String>,
    pub used_podlet: bool,
}

/// Generates systemd Quadlet `.container` unit files so the stack runs daemonless via Podman,
/// eliminating `dockerd`'s ~140-180 MB background memory footprint.
pub fn export_quadlet_units(
    compose_path: &Path,
    compose: &ParsedCompose,
    plan: &OptimizationPlan,
    output_dir: &Path,
    has_podlet: bool,
) -> Result<QuadletExportReport> {
    fs::create_dir_all(output_dir)?;
    let mut warnings = scan_podman_compatibility(compose);
    let mut generated_files = Vec::new();

    // If `podlet` is installed, prefer it for full Compose-to-Quadlet translation.
    if has_podlet {
        let out = Command::new("podlet")
            .args([
                "compose",
                &compose_path.to_string_lossy(),
                "--output",
                &output_dir.to_string_lossy(),
            ])
            .output();

        if let Ok(output) = out {
            if output.status.success() {
                if let Ok(entries) = fs::read_dir(output_dir) {
                    for entry in entries.flatten() {
                        generated_files.push(entry.path());
                    }
                }
                return Ok(QuadletExportReport {
                    output_dir: output_dir.to_path_buf(),
                    generated_files,
                    warnings,
                    used_podlet: true,
                });
            }
            warnings.push(format!(
                "`podlet` returned an error ({}); falling back to LeanDock built-in Quadlet generator",
                String::from_utf8_lossy(&output.stderr).trim()
            ));
        }
    }

    // Built-in deterministic Quadlet generator applying LeanDock's tuned memory limits & DB flags.
    for svc_plan in &plan.services {
        let Some(svc) = compose.services.get(&svc_plan.name) else {
            continue;
        };
        if svc_plan.offloaded_static {
            continue;
        }
        let Some(image) = svc_plan.minified_image.as_deref().or(svc.image.as_deref()) else {
            warnings.push(format!(
                "Service `{}` uses `build:` without an `image:` tag; build & tag it before enabling its Quadlet unit",
                svc.name
            ));
            continue;
        };

        let mut unit = String::new();
        unit.push_str(&format!(
            "# Generated by LeanDock Quadlet Exporter (Daemonless Podman)\n[Unit]\nDescription=LeanDock container {}\nAfter=network-online.target\n\n[Container]\nContainerName=leandock-{}\nImage={}\n",
            svc.name, svc.name, image
        ));

        for port in &svc.ports {
            unit.push_str(&format!("PublishPort={}\n", port));
        }
        for vol in &svc.volumes {
            unit.push_str(&format!("Volume={}\n", vol));
        }
        for (k, v) in &svc.environment {
            unit.push_str(&format!("Environment={}={}\n", k, v));
        }
        for (k, v) in &svc_plan.extra_env {
            unit.push_str(&format!("Environment={}={}\n", k, v));
        }
        if let Some(ref cmd) = svc_plan.tuned_command {
            unit.push_str(&format!("Exec={}\n", cmd.join(" ")));
        }
        if let Some(limit_mb) = svc_plan.mem_limit_mb {
            unit.push_str(&format!(
                "PodmanArgs=--memory={}m --log-opt max-size=10m\n",
                limit_mb
            ));
        }

        unit.push_str("\n[Service]\nRestart=on-failure\nMemoryKSM=yes\n\n[Install]\nWantedBy=default.target\n");

        let file_path = output_dir.join(format!("leandock-{}.container", svc.name));
        atomic_write_bytes(&file_path, unit.as_bytes())?;
        generated_files.push(file_path);
    }

    Ok(QuadletExportReport {
        output_dir: output_dir.to_path_buf(),
        generated_files,
        warnings,
        used_podlet: false,
    })
}
